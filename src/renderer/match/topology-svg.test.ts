import { describe, expect, it } from "vitest";
import type { TopologyFlow, TopologyFlowEdge, TopologyFlowNode, TopologyFlowNodeData } from "./topology-flow";
import { EDGE_HEALTH_COLOR } from "./topology-flow";
import type { TopologyEdgeHealth, TopologyEdgeKind } from "./topology-graph";
import { toSvg } from "./topology-svg";

const VCN = "ocid1.vcn.oc1.ap-tokyo-1.vcn1";
const SUBNET = "ocid1.subnet.oc1.ap-tokyo-1.a";
const INSTANCE = "ocid1.instance.oc1.ap-tokyo-1.i1";
const LB = "ocid1.loadbalancer.oc1.ap-tokyo-1.lb1";
const NAT = "ocid1.natgateway.oc1.ap-tokyo-1.nat1";

const SEGMENT = [
  { x: 10, y: 20 },
  { x: 10, y: 60 },
  { x: 90, y: 60 },
];

const EDGE_LABEL: Partial<Record<TopologyEdgeKind, string>> = {
  backend: "LB → Instance",
  route: "Subnet → Gateway",
  attachment: "Instance → Volume",
  // 通信許可エッジは種別名でなくポート要約が線のラベルになる。
  "sl-allow": "tcp/443",
};

const EDGE_COLOR: Partial<Record<TopologyEdgeKind, string>> = {
  backend: "#7ea6d8",
  route: "#8b9196",
  attachment: "#d289cb",
  "sl-allow": "#b8c26a",
};

function dataOf(extra: Partial<TopologyFlowNodeData> = {}): TopologyFlowNodeData {
  return { variant: "resource", label: "node", searchText: [], status: "ok", expandable: false, ...extra };
}

function container(
  id: string,
  box: Partial<TopologyFlowNode> = {},
  data: Partial<TopologyFlowNodeData> = {},
): TopologyFlowNode {
  return {
    id,
    type: "container",
    position: { x: 0, y: 0 },
    width: 240,
    height: 120,
    ...box,
    data: dataOf({ variant: "container", ...data }),
  };
}

function resource(
  id: string,
  box: Partial<TopologyFlowNode> = {},
  data: Partial<TopologyFlowNodeData> = {},
): TopologyFlowNode {
  return {
    id,
    type: "resource",
    position: { x: 0, y: 0 },
    width: 168,
    height: 56,
    ...box,
    data: dataOf(data),
  };
}

function edge(kind: TopologyEdgeKind, source: string, target: string, points = SEGMENT): TopologyFlowEdge {
  return {
    id: `${kind}|${source}|${target}`,
    source,
    target,
    sourceSide: "bottom",
    targetSide: "top",
    sourceHandle: "s-bottom",
    targetHandle: "t-top",
    points,
    kind,
    label: EDGE_LABEL[kind] as string,
    color: EDGE_COLOR[kind] as string,
  };
}

/** toTopologyFlowと同じく、健全性を持つエッジはヘルス色で塗られた状態で渡ってくる。 */
function healthEdge(source: string, target: string, health: TopologyEdgeHealth): TopologyFlowEdge {
  return { ...edge("backend", source, target), health, color: EDGE_HEALTH_COLOR[health] };
}

function flowOf(nodes: TopologyFlowNode[], edges: TopologyFlowEdge[] = []): TopologyFlow {
  return { nodes, edges };
}

describe("toSvg", () => {
  it("wraps the output in a standalone svg root with a painted background", () => {
    const svg = toSvg(flowOf([]));
    expect(svg.startsWith('<svg xmlns="http://www.w3.org/2000/svg"')).toBe(true);
    expect(svg.endsWith("</svg>")).toBe(true);
    expect(svg).toContain('fill="#ffffff"');
    expect(svg).not.toContain("<script");
    expect(svg).not.toContain("http://www.w3.org/1999/xhtml");
  });

  it("names the generator in the title and the header line", () => {
    const svg = toSvg(flowOf([]));
    expect(svg).toContain("<title>generated by freelens-oci-cluster</title>");
    expect(svg).toContain(">generated by freelens-oci-cluster</text>");
  });

  it("puts the cluster name and compartment before the generator name", () => {
    const svg = toSvg(flowOf([]), { clusterName: "demo", compartmentId: "ocid1.compartment.oc1..c1" });
    expect(svg).toContain(">demo / ocid1.compartment.oc1..c1 / generated by freelens-oci-cluster</text>");
  });

  it("drops the missing meta fields and keeps the generator name", () => {
    expect(toSvg(flowOf([]), { clusterName: "demo" })).toContain(">demo / generated by freelens-oci-cluster</text>");
    expect(toSvg(flowOf([]), {})).toContain(">generated by freelens-oci-cluster</text>");
  });

  it("draws a container with its kind label, name and CIDR", () => {
    const svg = toSvg(
      flowOf([container(VCN, {}, { kind: "vcn", kindLabel: "VCN", label: "prod-vcn", sublabel: "10.0.0.0/16" })]),
    );
    expect(svg).toContain(">VCN</text>");
    expect(svg).toContain(">prod-vcn</text>");
    expect(svg).toContain(">10.0.0.0/16</text>");
    expect(svg).toContain('stroke-dasharray="4 3"');
  });

  it("draws a resource with its kind label and name", () => {
    const svg = toSvg(flowOf([resource(INSTANCE, {}, { kind: "instance", kindLabel: "Instance", label: "worker-1" })]));
    expect(svg).toContain(">INSTANCE</text>");
    expect(svg).toContain(">worker-1</text>");
  });

  it("omits the click affordance from an expandable kind label", () => {
    const svg = toSvg(
      flowOf([
        resource(
          "instance-group:x",
          {},
          { kind: "instance-group", kindLabel: "Instances", label: "12 nodes", expandable: true },
        ),
      ]),
    );
    expect(svg).toContain(">INSTANCES</text>");
    expect(svg).not.toContain("click to expand");
  });

  it("colors the left accent of a warning node and leaves the others on the border color", () => {
    const warning = toSvg(flowOf([resource(LB, {}, { kindLabel: "LB", label: "public-lb", status: "warning" })]));
    expect(warning).toContain('width="3" height="55" rx="1.5" fill="#e0a45a"');
    const ok = toSvg(flowOf([resource(LB, {}, { kindLabel: "LB", label: "public-lb", status: "ok" })]));
    expect(ok).toContain('width="3" height="55" rx="1.5" fill="#c3c7cb"');
    const unknown = toSvg(flowOf([resource(LB, {}, { kindLabel: "LB", label: "public-lb", status: "unknown" })]));
    expect(unknown).toContain('width="3" height="55" rx="1.5" fill="#c3c7cb"');
  });

  it("resolves a child position against its parent so both sit in one coordinate space", () => {
    const svg = toSvg(
      flowOf([
        container(VCN, { position: { x: 0, y: 0 }, width: 400, height: 300 }, { kindLabel: "VCN", label: "vcn" }),
        container(SUBNET, { parentId: VCN, position: { x: 56, y: 98 }, width: 200, height: 100 }, { label: "subnet" }),
        resource(INSTANCE, { parentId: SUBNET, position: { x: 32, y: 74 } }, { label: "worker-1" }),
      ]),
    );
    expect(svg).toContain('<rect x="0.5" y="0.5" width="399" height="299"');
    expect(svg).toContain('<rect x="56.5" y="98.5" width="199" height="99"');
    expect(svg).toContain('<rect x="88.5" y="172.5" width="167" height="55"');
  });

  it("shifts the drawing so a negative coordinate stays inside the canvas", () => {
    const svg = toSvg(flowOf([resource(LB, { position: { x: -40, y: -10 } })]));
    expect(svg).toContain('<g transform="translate(64,62)">');
  });

  it("turns the routed points into a polyline with the edge color and an arrow marker", () => {
    const svg = toSvg(flowOf([resource(LB), resource(INSTANCE)], [edge("backend", LB, INSTANCE)]));
    expect(svg).toContain('<polyline points="10,20 10,60 90,60" fill="none" stroke="#7ea6d8"');
    expect(svg).toContain('marker-end="url(#oci-arrow-backend)"');
    expect(svg).toContain("<title>LB → Instance</title>");
  });

  it("dims and dashes the route edges", () => {
    const svg = toSvg(flowOf([resource(SUBNET), resource(NAT)], [edge("route", SUBNET, NAT)]));
    expect(svg).toContain('<g opacity="0.45">');
    expect(svg).toContain('stroke-dasharray="4 4"');
  });

  it("dashes the security edges without dimming them, and names them by meaning in the legend", () => {
    const svg = toSvg(flowOf([resource(SUBNET), resource(NAT)], [edge("sl-allow", SUBNET, NAT)]));
    expect(svg).toContain('stroke-dasharray="6 3"');
    expect(svg).not.toContain('<g opacity="0.45">');
    expect(svg).toContain("<title>tcp/443</title>");
    expect(svg).toContain(">Allowed by Security List</text>");
  });

  it("defines an arrow marker only for the edge kinds present", () => {
    const svg = toSvg(flowOf([resource(LB), resource(INSTANCE)], [edge("backend", LB, INSTANCE)]));
    expect(svg).toContain('<marker id="oci-arrow-backend"');
    expect(svg).not.toContain('<marker id="oci-arrow-route"');
  });

  it("draws a health-colored backend edge with its own arrow marker", () => {
    const svg = toSvg(
      flowOf([resource(LB), resource(INSTANCE), resource(NAT)], [healthEdge(LB, INSTANCE, "critical")]),
    );
    expect(svg).toContain(`stroke="${EDGE_HEALTH_COLOR.critical}"`);
    expect(svg).toContain('marker-end="url(#oci-arrow-backend-critical)"');
    expect(svg).toContain(`<marker id="oci-arrow-backend-critical"`);
    expect(svg).toContain(`<path d="M 0 0 L 10 5 L 0 10 z" fill="${EDGE_HEALTH_COLOR.critical}"/>`);
    expect(svg).not.toContain('<marker id="oci-arrow-backend"');
  });

  it("defines one marker per health state present on the backend edges", () => {
    const svg = toSvg(
      flowOf(
        [resource(LB), resource(INSTANCE), resource(NAT)],
        [healthEdge(LB, INSTANCE, "ok"), healthEdge(LB, NAT, "warning"), edge("route", SUBNET, NAT)],
      ),
    );
    expect([...svg.matchAll(/<marker id="([^"]+)"/g)].map((match) => match[1])).toEqual([
      "oci-arrow-backend-ok",
      "oci-arrow-backend-warning",
      "oci-arrow-route",
    ]);
  });

  it("replaces the kind legend row with the health rows once every edge of that kind is colored", () => {
    const svg = toSvg(
      flowOf(
        [resource(LB), resource(INSTANCE), resource(NAT)],
        [healthEdge(LB, INSTANCE, "critical"), healthEdge(LB, NAT, "ok"), edge("route", SUBNET, NAT)],
      ),
    );
    const labels = [...svg.matchAll(/>(Backend [A-Za-z]+|[^<>]+ → [^<>]+)<\/text>/g)].map((match) => match[1]);
    expect(labels).toEqual(["Subnet → Gateway", "Backend OK", "Backend Critical"]);
  });

  it("keeps the kind legend row while the kind still has an edge without health", () => {
    const svg = toSvg(
      flowOf(
        [resource(LB), resource(INSTANCE), resource(NAT)],
        [healthEdge(LB, INSTANCE, "unknown"), edge("backend", LB, NAT)],
      ),
    );
    const labels = [...svg.matchAll(/>(Backend [A-Za-z]+|[^<>]+ → [^<>]+)<\/text>/g)].map((match) => match[1]);
    expect(labels).toEqual(["LB → Instance", "Backend Unknown"]);
  });

  it("skips an edge without a routed polyline", () => {
    const svg = toSvg(flowOf([resource(LB), resource(INSTANCE)], [edge("backend", LB, INSTANCE, [])]));
    expect(svg).not.toContain("<polyline");
  });

  it("lists only the edge kinds used, in the declaration order", () => {
    const svg = toSvg(
      flowOf(
        [resource(LB), resource(INSTANCE), resource(SUBNET), resource(NAT)],
        [edge("route", SUBNET, NAT), edge("attachment", INSTANCE, LB), edge("backend", LB, INSTANCE)],
      ),
    );
    const labels = [...svg.matchAll(/>([^<>]+ → [^<>]+)<\/text>/g)].map((match) => match[1]);
    expect(labels).toEqual(["LB → Instance", "Instance → Volume", "Subnet → Gateway"]);
  });

  it("omits the legend when the graph has no edge", () => {
    expect(toSvg(flowOf([resource(LB)]))).not.toContain("<line");
  });

  it("escapes the XML metacharacters in every label", () => {
    const svg = toSvg(flowOf([resource(LB, {}, { kindLabel: "LB", label: "<b> & \"q\" 'a'" })]), {
      clusterName: "a<b>&c",
    });
    expect(svg).toContain("&lt;b&gt; &amp; &quot;q&quot; &apos;a&apos;");
    expect(svg).toContain("a&lt;b&gt;&amp;c / generated by freelens-oci-cluster");
    expect(svg).not.toContain("<b>");
  });

  it("truncates a name that would overflow its box but keeps it whole in the tooltip", () => {
    const long = "a".repeat(200);
    const svg = toSvg(flowOf([resource(INSTANCE, {}, { kindLabel: "Instance", label: long })]));
    expect(svg).not.toContain(`>${long}</text>`);
    expect(svg).toContain("…</text>");
    expect(svg).toContain(`<title>${long}</title>`);
  });

  it("returns the same text for the same input", () => {
    const build = () =>
      toSvg(
        flowOf(
          [container(VCN, {}, { kindLabel: "VCN", label: "vcn" }), resource(INSTANCE, { parentId: VCN })],
          [edge("backend", LB, INSTANCE)],
        ),
        { clusterName: "demo" },
      );
    expect(build()).toBe(build());
  });
});
