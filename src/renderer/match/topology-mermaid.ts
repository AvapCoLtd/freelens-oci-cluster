import { EDGE_HEALTH_LEVELS } from "./backend-health";
import { pushToMap } from "./map-list";
import {
  EDGE_HEALTH_COLOR,
  EDGE_HEALTH_DASH,
  EDGE_HEALTH_LABEL,
  EDGE_KIND_COLOR,
  EDGE_KIND_DASH,
  EDGE_KIND_LABEL,
  MERMAID_DASH_EXCLUDED,
  missingKindLabel,
  NODE_KIND_LABEL,
} from "./topology-flow";
import {
  TOPOLOGY_EDGE_KINDS,
  type TopologyEdgeHealth,
  type TopologyEdgeKind,
  type TopologyGraph,
  type TopologyNode,
  type TopologyNodeStatus,
} from "./topology-graph";
import type { TopologyNodeKind } from "./topology-order";

const HEADER = "flowchart TB";
const INDENT = "  ";
const GENERATED_BY = "generated by freelens-oci-cluster";

const STATUS_STYLE: Partial<Record<TopologyNodeStatus, string>> = {
  warning: "stroke:#e0a45a,stroke-width:2px",
  unknown: "stroke:#9aa0a6,stroke-dasharray:4 3",
};

const STATUS_ORDER: readonly TopologyNodeStatus[] = ["warning", "unknown"];

const STATUS_LEGEND: Partial<Record<TopologyNodeStatus, string>> = {
  warning: "abnormal state or orphaned PV (orange border)",
  unknown: "state unknown (gray dashed border)",
};

const K8S_KINDS: ReadonlySet<TopologyNodeKind> = new Set(["k8s-service", "k8s-pv"]);

/** 親を持たないノードを載せる領域。idは連番(nX)と衝突しない固定値。 */
const DOMAINS: readonly { id: string; label: string; holds: (node: TopologyNode) => boolean }[] = [
  { id: "k8s", label: "Kubernetes", holds: (node) => K8S_KINDS.has(node.kind) },
  { id: "oci", label: "OCI", holds: (node) => !K8S_KINDS.has(node.kind) },
];

// #の置換を先に行わない場合、後続の置換が生む#quot;自体を壊す。
function escapeLabel(value: string): string {
  return value
    .replace(/#/g, "#35;")
    .replace(/%/g, "#37;")
    .replace(/"/g, "#quot;")
    .replace(/</g, "#60;")
    .replace(/>/g, "#62;")
    .replace(/\s+/g, " ")
    .trim();
}

// <br/>はエスケープ後に足す: エスケープに通すと#60;br/#62;になり改行として働かない。
function labelOf(node: TopologyNode): string {
  const head = escapeLabel(`[${NODE_KIND_LABEL[node.kind]}] ${node.label}`);
  const summary = node.summary ? escapeLabel(node.summary) : "";
  return summary === "" ? head : `${head}<br/>${summary}`;
}

/** 先頭コメント行に添える出所。ページ側が持つクラスタ情報をここへ渡す。 */
export interface TopologyMermaidMeta {
  clusterName?: string;
  compartmentId?: string;
}

/**
 * トポロジー図をMermaid flowchartのテキストへ書き出す。
 * 同一入力に対し同一出力を返す純粋関数で、ノードidは図のOCIDではなくnodes配列順の連番になる。
 */
export function toMermaid(graph: TopologyGraph, meta?: TopologyMermaidMeta): string {
  const idOf = new Map<string, string>();
  for (const [index, node] of graph.nodes.entries()) idOf.set(node.id, `n${index + 1}`);

  const childrenOf = new Map<string, TopologyNode[]>();
  const roots: TopologyNode[] = [];
  for (const node of graph.nodes) {
    const parentId = node.parentId;
    if (parentId === undefined || parentId === node.id || !idOf.has(parentId)) {
      roots.push(node);
      continue;
    }
    pushToMap(childrenOf, parentId, node);
  }

  const lines: string[] = [];
  if (meta) {
    const parts = [meta.clusterName, meta.compartmentId]
      .filter((part): part is string => !!part)
      .map((part) => part.replace(/\s+/g, " ").trim());
    lines.push(`%% ${[...parts, GENERATED_BY].join(" / ")}`);
  }
  lines.push(HEADER);
  const emitted = new Set<string>();
  const emit = (node: TopologyNode, depth: number) => {
    if (emitted.has(node.id)) return;
    emitted.add(node.id);
    const indent = INDENT.repeat(depth + 1);
    const id = idOf.get(node.id) ?? node.id;
    const children = childrenOf.get(node.id);
    if (!children) {
      lines.push(`${indent}${id}["${labelOf(node)}"]`);
      return;
    }
    lines.push(`${indent}subgraph ${id}["${labelOf(node)}"]`);
    for (const child of children) emit(child, depth + 1);
    lines.push(`${indent}end`);
  };
  for (const domain of DOMAINS) {
    const members = roots.filter((node) => domain.holds(node));
    if (members.length === 0) continue;
    lines.push(`${INDENT}subgraph ${domain.id}["${domain.label}"]`);
    for (const node of members) emit(node, 1);
    lines.push(`${INDENT}end`);
  }
  // parentIdが循環した入力ではrootsから辿れないノードが残る。
  for (const node of graph.nodes) emit(node, 0);

  const edgeLinesStart = lines.length;
  const linkIndexesByKind = new Map<TopologyEdgeKind, number[]>();
  const linkIndexesByHealth = new Map<TopologyEdgeHealth, number[]>();
  for (const edge of graph.edges) {
    const source = idOf.get(edge.source);
    const target = idOf.get(edge.target);
    if (!source || !target) continue;
    const index = lines.length - edgeLinesStart;
    // health色で塗る分を種別色から外す: 同じlinkへ2本のlinkStyleを出すと後勝ちに依存する。
    if (edge.health) pushToMap(linkIndexesByHealth, edge.health, index);
    else pushToMap(linkIndexesByKind, edge.kind, index);
    lines.push(`${INDENT}${source} -->|${edge.label ?? EDGE_KIND_LABEL[edge.kind]}| ${target}`);
  }
  for (const [kind, indexes] of linkIndexesByKind) {
    const dash = MERMAID_DASH_EXCLUDED.has(kind) ? undefined : EDGE_KIND_DASH[kind];
    const style = dash === undefined ? "" : `,stroke-dasharray:${dash}`;
    lines.push(`${INDENT}linkStyle ${indexes.join(",")} stroke:${EDGE_KIND_COLOR[kind]}${style}`);
  }
  for (const health of EDGE_HEALTH_LEVELS) {
    const indexes = linkIndexesByHealth.get(health);
    if (!indexes) continue;
    const dash = EDGE_HEALTH_DASH[health];
    const style = dash === undefined ? "" : `,stroke-dasharray:${dash}`;
    lines.push(`${INDENT}linkStyle ${indexes.join(",")} stroke:${EDGE_HEALTH_COLOR[health]}${style}`);
  }

  const idsByStatus = new Map<TopologyNodeStatus, string[]>();
  for (const node of graph.nodes) {
    const status = node.status;
    const id = idOf.get(node.id);
    if (!status || !id || !STATUS_STYLE[status]) continue;
    pushToMap(idsByStatus, status, id);
  }
  if (idsByStatus.size > 0) {
    for (const status of STATUS_ORDER) {
      const ids = idsByStatus.get(status);
      if (!ids) continue;
      lines.push(`${INDENT}classDef ${status} ${STATUS_STYLE[status]}`);
      lines.push(`${INDENT}class ${ids.join(",")} ${status}`);
    }
  }

  for (const missing of graph.missing) {
    lines.push(`${INDENT}%% missing: ${missing.target} ${missingKindLabel(missing)} (${missing.sections.join(", ")})`);
  }

  const legend: string[] = [];
  for (const kind of TOPOLOGY_EDGE_KINDS) {
    if (linkIndexesByKind.has(kind)) legend.push(`${EDGE_KIND_LABEL[kind]} : ${EDGE_KIND_COLOR[kind]}`);
  }
  for (const health of EDGE_HEALTH_LEVELS) {
    if (linkIndexesByHealth.has(health)) legend.push(`${EDGE_HEALTH_LABEL[health]} : ${EDGE_HEALTH_COLOR[health]}`);
  }
  for (const status of STATUS_ORDER) {
    const meaning = STATUS_LEGEND[status];
    if (meaning && idsByStatus.has(status)) legend.push(`${status} : ${meaning}`);
  }
  if (legend.length > 0) {
    lines.push(`${INDENT}%% legend:`, ...legend.map((entry) => `${INDENT}%%   ${entry}`));
  }

  return lines.join("\n");
}
