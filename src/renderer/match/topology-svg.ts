import { EDGE_HEALTH_LEVELS } from "./backend-health";
import type { TopologyFlow, TopologyFlowEdge, TopologyFlowNode, TopologyFlowNodeData } from "./topology-flow";
import {
  EDGE_HEALTH_COLOR,
  EDGE_HEALTH_DASH,
  EDGE_HEALTH_LABEL,
  EDGE_KIND_COLOR,
  EDGE_KIND_DASH,
  EDGE_KIND_LABEL,
  EDGE_KIND_OPACITY,
  edgeDashOf,
} from "./topology-flow";
import { TOPOLOGY_EDGE_KINDS } from "./topology-graph";

const GENERATED_BY = "generated by freelens-oci-cluster";

const FONT_FAMILY = "'Segoe UI', 'Helvetica Neue', Helvetica, Arial, sans-serif";

const BACKGROUND = "#ffffff";
const CONTAINER_FILL = "#f7f8f9";
const CONTAINER_BORDER = "#c3c7cb";
const RESOURCE_FILL = "#ffffff";
const RESOURCE_BORDER = "#c3c7cb";
const WARNING_COLOR = "#e0a45a";
const TEXT_PRIMARY = "#202124";
const TEXT_SECONDARY = "#6b7075";

interface Font {
  size: number;
  line: number;
}

const KIND_FONT: Font = { size: 10, line: 12 };
const NAME_FONT: Font = { size: 12, line: 16 };
const CONTAINER_NAME_FONT: Font = { size: 13, line: 17 };
const CIDR_FONT: Font = { size: 11, line: 15 };
const HEADER_FONT: Font = { size: 12, line: 16 };
const LEGEND_FONT: Font = { size: 10, line: 12 };

const KIND_LETTER_SPACING = 0.4;

/** 画面のCSSボックス(border+padding)を座標へ展開した値。 */
const CONTAINER_INSET = { top: 9, left: 13, right: 13 };
const RESOURCE_INSET = { left: 13, right: 11 };
const RESOURCE_CONTENT_HEIGHT = KIND_FONT.line + 2 + NAME_FONT.line;

const CONTAINER_RADIUS = 6;
const RESOURCE_RADIUS = 4;
const RESOURCE_ACCENT_WIDTH = 3;

const EDGE_STROKE_WIDTH = 1.5;
const CONTAINER_DASH = "4 3";

const MARGIN = 24;
const HEADER_GAP = 12;
const LEGEND_GAP = 20;
const LEGEND_PADDING = { x: 8, y: 6 };
const LEGEND_ROW_GAP = 3;
const LEGEND_SAMPLE_WIDTH = 16;
const LEGEND_SAMPLE_GAP = 6;

/** SVGでは実測幅が取れない。半角1文字あたりこの比をfontSizeに掛けて推定する。 */
const NARROW_RATIO = 0.6;
/** 全角として数える範囲(CJK・かな・ハングル・全角記号)。 */
const WIDE_CHAR = /[ᄀ-ᅟ⺀-〾ぁ-㏿㐀-䶿一-鿿ꀀ-꓏가-힣豈-﫿︰-﹯＀-｠￠-￦]/;
const ELLIPSIS = "…";

// &の置換を先に行わない場合、後続の置換が生む&lt;等のアンパサンド自体を二重変換する。
function escapeXml(value: string): string {
  return value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&apos;");
}

function charWidth(char: string, fontSize: number): number {
  return (WIDE_CHAR.test(char) ? 1 : NARROW_RATIO) * fontSize;
}

function textWidth(text: string, fontSize: number): number {
  let width = 0;
  for (const char of text) width += charWidth(char, fontSize);
  return width;
}

function fitText(text: string, fontSize: number, maxWidth: number): string {
  if (textWidth(text, fontSize) <= maxWidth) return text;
  let width = textWidth(ELLIPSIS, fontSize);
  const kept: string[] = [];
  for (const char of text) {
    const grown = width + charWidth(char, fontSize);
    if (grown > maxWidth) break;
    kept.push(char);
    width = grown;
  }
  return kept.length === 0 ? "" : `${kept.join("")}${ELLIPSIS}`;
}

// 0.8はフォントのascent比。行送りの中央へ字面を置いたときのベースライン位置になる。
function baselineOf(top: number, font: Font): number {
  return top + (font.line - font.size) / 2 + font.size * 0.8;
}

function num(value: number): string {
  return String(Math.round(value * 100) / 100);
}

interface Rect {
  x: number;
  y: number;
  width: number;
  height: number;
}

/** ノードは親が子より前に並ぶため、1パスで親の絶対座標が引ける。 */
function absoluteRects(nodes: readonly TopologyFlowNode[]): Map<string, Rect> {
  const rects = new Map<string, Rect>();
  for (const node of nodes) {
    const origin = node.parentId ? rects.get(node.parentId) : undefined;
    rects.set(node.id, {
      x: (origin?.x ?? 0) + node.position.x,
      y: (origin?.y ?? 0) + node.position.y,
      width: node.width,
      height: node.height,
    });
  }
  return rects;
}

function textEl(x: number, y: number, font: Font, fill: string, text: string, extra = ""): string {
  return `<text x="${num(x)}" y="${num(y)}" font-size="${font.size}" fill="${fill}"${extra}>${escapeXml(text)}</text>`;
}

function kindTextEl(x: number, y: number, fill: string, text: string, maxWidth: number): string {
  const upper = fitText(text.toUpperCase(), KIND_FONT.size, maxWidth);
  return textEl(x, y, KIND_FONT, fill, upper, ` letter-spacing="${KIND_LETTER_SPACING}"`);
}

function titleEl(text: string): string {
  return `<title>${escapeXml(text)}</title>`;
}

function containerSvg(rect: Rect, data: TopologyFlowNodeData): string {
  const inner = rect.width - CONTAINER_INSET.left - CONTAINER_INSET.right;
  const x = rect.x + CONTAINER_INSET.left;
  const parts = [
    `<rect x="${num(rect.x + 0.5)}" y="${num(rect.y + 0.5)}" width="${num(rect.width - 1)}" height="${num(rect.height - 1)}" rx="${CONTAINER_RADIUS}" fill="${CONTAINER_FILL}" stroke="${CONTAINER_BORDER}" stroke-dasharray="${CONTAINER_DASH}"/>`,
  ];
  let top = rect.y + CONTAINER_INSET.top;
  if (data.kindLabel) {
    parts.push(kindTextEl(x, baselineOf(top, KIND_FONT), TEXT_SECONDARY, data.kindLabel, inner));
    top += KIND_FONT.line;
  }
  const name = fitText(data.label, CONTAINER_NAME_FONT.size, inner);
  parts.push(
    textEl(x, baselineOf(top, CONTAINER_NAME_FONT), CONTAINER_NAME_FONT, TEXT_PRIMARY, name, ' font-weight="bold"'),
  );
  top += CONTAINER_NAME_FONT.line;
  if (data.sublabel) {
    const cidr = fitText(data.sublabel, CIDR_FONT.size, inner);
    parts.push(textEl(x, baselineOf(top, CIDR_FONT), CIDR_FONT, TEXT_SECONDARY, cidr));
  }
  return `<g>${titleEl(data.label)}${parts.join("")}</g>`;
}

function resourceSvg(rect: Rect, data: TopologyFlowNodeData): string {
  const warning = data.status === "warning";
  const accent = warning ? WARNING_COLOR : RESOURCE_BORDER;
  const inner = rect.width - RESOURCE_INSET.left - RESOURCE_INSET.right;
  const x = rect.x + RESOURCE_INSET.left;
  const top = rect.y + (rect.height - RESOURCE_CONTENT_HEIGHT) / 2;
  const parts = [
    `<rect x="${num(rect.x + 0.5)}" y="${num(rect.y + 0.5)}" width="${num(rect.width - 1)}" height="${num(rect.height - 1)}" rx="${RESOURCE_RADIUS}" fill="${RESOURCE_FILL}" stroke="${RESOURCE_BORDER}"/>`,
    `<rect x="${num(rect.x + 0.5)}" y="${num(rect.y + 0.5)}" width="${RESOURCE_ACCENT_WIDTH}" height="${num(rect.height - 1)}" rx="1.5" fill="${accent}"/>`,
  ];
  if (data.kindLabel) {
    parts.push(
      kindTextEl(x, baselineOf(top, KIND_FONT), warning ? WARNING_COLOR : TEXT_SECONDARY, data.kindLabel, inner),
    );
  }
  const name = fitText(data.label, NAME_FONT.size, inner);
  parts.push(textEl(x, baselineOf(top + KIND_FONT.line + 2, NAME_FONT), NAME_FONT, TEXT_PRIMARY, name));
  return `<g>${titleEl(data.label)}${parts.join("")}</g>`;
}

function markerId(edge: Pick<TopologyFlowEdge, "kind" | "health">): string {
  return edge.health ? `oci-arrow-${edge.kind}-${edge.health}` : `oci-arrow-${edge.kind}`;
}

/** defsへ出す矢印マーカー。色はエッジと同じ値でなければ矢印だけ別色になる。 */
function markersOf(edges: readonly TopologyFlowEdge[]): { id: string; color: string }[] {
  const byId = new Map<string, { id: string; color: string }>();
  for (const kind of TOPOLOGY_EDGE_KINDS) {
    for (const edge of edges) {
      if (edge.kind !== kind) continue;
      const id = markerId(edge);
      if (!byId.has(id)) byId.set(id, { id, color: edge.color });
    }
  }
  return [...byId.values()];
}

function markerSvg(marker: { id: string; color: string }): string {
  return `<marker id="${marker.id}" viewBox="0 0 10 10" refX="9" refY="5" markerUnits="userSpaceOnUse" markerWidth="10" markerHeight="10" orient="auto-start-reverse"><path d="M 0 0 L 10 5 L 0 10 z" fill="${marker.color}"/></marker>`;
}

function dashAttr(edge: TopologyFlowEdge): string {
  const dash = edgeDashOf(edge);
  return dash === undefined ? "" : ` stroke-dasharray="${dash}"`;
}

function edgeSvg(edge: TopologyFlowEdge): string {
  if (edge.points.length < 2) return "";
  const points = edge.points.map((point) => `${num(point.x)},${num(point.y)}`).join(" ");
  const faded = EDGE_KIND_OPACITY[edge.kind];
  // 破線の薄さはpolyline側のstroke-opacityでは矢印マーカーに載らない。要素全体のopacityで下げる。
  const opacity = faded === undefined ? "" : ` opacity="${faded}"`;
  const line = `<polyline points="${points}" fill="none" stroke="${edge.color}" stroke-width="${EDGE_STROKE_WIDTH}" stroke-linejoin="round" marker-end="url(#${markerId(edge)})"${dashAttr(edge)}/>`;
  return `<g${opacity}>${titleEl(edge.label)}${line}</g>`;
}

interface Legend {
  svg: (x: number, y: number) => string;
  width: number;
  height: number;
}

interface LegendRow {
  color: string;
  label: string;
  dash?: string;
  opacity?: number;
}

/**
 * 凡例の行。health色で塗ったbackendエッジは種別色の行に現れない
 * (その色の線が図に無い行を出すと対応が読めなくなる)。
 */
function legendRowsOf(edges: readonly TopologyFlowEdge[]): LegendRow[] {
  const rows: LegendRow[] = [];
  for (const kind of TOPOLOGY_EDGE_KINDS) {
    if (!edges.some((edge) => edge.kind === kind && !edge.health)) continue;
    rows.push({
      color: EDGE_KIND_COLOR[kind],
      label: EDGE_KIND_LABEL[kind],
      dash: EDGE_KIND_DASH[kind],
      opacity: EDGE_KIND_OPACITY[kind],
    });
  }
  for (const health of EDGE_HEALTH_LEVELS) {
    if (!edges.some((edge) => edge.health === health)) continue;
    rows.push({ color: EDGE_HEALTH_COLOR[health], label: EDGE_HEALTH_LABEL[health], dash: EDGE_HEALTH_DASH[health] });
  }
  return rows;
}

function legendOf(rows: readonly LegendRow[]): Legend | undefined {
  if (rows.length === 0) return undefined;
  const textLeft = LEGEND_PADDING.x + LEGEND_SAMPLE_WIDTH + LEGEND_SAMPLE_GAP;
  const width = textLeft + Math.max(...rows.map((row) => textWidth(row.label, LEGEND_FONT.size))) + LEGEND_PADDING.x;
  const height = LEGEND_PADDING.y * 2 + rows.length * LEGEND_FONT.line + (rows.length - 1) * LEGEND_ROW_GAP;
  return {
    width,
    height,
    svg: (x, y) => {
      const parts = [
        `<rect x="${num(x + 0.5)}" y="${num(y + 0.5)}" width="${num(width - 1)}" height="${num(height - 1)}" rx="${RESOURCE_RADIUS}" fill="${RESOURCE_FILL}" stroke="${RESOURCE_BORDER}"/>`,
      ];
      for (const [index, row] of rows.entries()) {
        const top = y + LEGEND_PADDING.y + index * (LEGEND_FONT.line + LEGEND_ROW_GAP);
        const middle = top + LEGEND_FONT.line / 2;
        const dash = row.dash === undefined ? "" : ` stroke-dasharray="${row.dash}"`;
        const opacity = row.opacity === undefined ? "" : ` opacity="${row.opacity}"`;
        parts.push(
          `<line x1="${num(x + LEGEND_PADDING.x)}" y1="${num(middle)}" x2="${num(x + LEGEND_PADDING.x + LEGEND_SAMPLE_WIDTH)}" y2="${num(middle)}" stroke="${row.color}" stroke-width="2"${dash}${opacity}/>`,
        );
        parts.push(textEl(x + textLeft, baselineOf(top, LEGEND_FONT), LEGEND_FONT, TEXT_SECONDARY, row.label));
      }
      return parts.join("");
    },
  };
}

export interface TopologySvgMeta {
  clusterName?: string;
  compartmentId?: string;
}

function headerTextOf(meta: TopologySvgMeta | undefined): string {
  const parts = [meta?.clusterName, meta?.compartmentId]
    .filter((part): part is string => !!part)
    .map((part) => part.replace(/\s+/g, " ").trim());
  return [...parts, GENERATED_BY].join(" / ");
}

interface Bounds {
  minX: number;
  minY: number;
  maxX: number;
  maxY: number;
}

function boundsOf(rects: Iterable<Rect>, flow: TopologyFlow): Bounds {
  let minX = Number.POSITIVE_INFINITY;
  let minY = Number.POSITIVE_INFINITY;
  let maxX = Number.NEGATIVE_INFINITY;
  let maxY = Number.NEGATIVE_INFINITY;
  const cover = (x: number, y: number) => {
    minX = Math.min(minX, x);
    minY = Math.min(minY, y);
    maxX = Math.max(maxX, x);
    maxY = Math.max(maxY, y);
  };
  for (const rect of rects) {
    cover(rect.x, rect.y);
    cover(rect.x + rect.width, rect.y + rect.height);
  }
  for (const edge of flow.edges) {
    for (const point of edge.points) cover(point.x, point.y);
  }
  if (minX === Number.POSITIVE_INFINITY) return { minX: 0, minY: 0, maxX: 0, maxY: 0 };
  return { minX, minY, maxX, maxY };
}

/** 同一入力に対し同一出力を返す純粋関数で、外部CSS・スクリプト・フォントを参照しない。 */
export function toSvg(flow: TopologyFlow, meta?: TopologySvgMeta): string {
  const rects = absoluteRects(flow.nodes);
  const bounds = boundsOf(rects.values(), flow);
  const markers = markersOf(flow.edges);
  const legend = legendOf(legendRowsOf(flow.edges));

  const header = headerTextOf(meta);
  const headerHeight = HEADER_FONT.line + HEADER_GAP;
  const contentWidth = bounds.maxX - bounds.minX;
  const contentHeight = bounds.maxY - bounds.minY;
  const bodyWidth = Math.max(contentWidth, legend?.width ?? 0, textWidth(header, HEADER_FONT.size));
  const width = Math.ceil(bodyWidth + MARGIN * 2);
  const height = Math.ceil(MARGIN * 2 + headerHeight + contentHeight + (legend ? LEGEND_GAP + legend.height : 0));

  const contentTop = MARGIN + headerHeight;
  const nodes: string[] = [];
  for (const node of flow.nodes) {
    const rect = rects.get(node.id);
    if (!rect) continue;
    nodes.push(node.type === "container" ? containerSvg(rect, node.data) : resourceSvg(rect, node.data));
  }
  // エッジは画面と同じく全ノードの上に載せる(親コンテナを跨ぐ線が箱の下へ潜らない)。
  const edges = flow.edges.map(edgeSvg);

  const body = [
    `<g transform="translate(${num(MARGIN - bounds.minX)},${num(contentTop - bounds.minY)})">`,
    ...nodes,
    ...edges,
    "</g>",
  ].join("");

  return [
    `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}" font-family="${escapeXml(FONT_FAMILY)}">`,
    titleEl(header),
    `<defs>${markers.map(markerSvg).join("")}</defs>`,
    `<rect width="${width}" height="${height}" fill="${BACKGROUND}"/>`,
    textEl(MARGIN, baselineOf(MARGIN, HEADER_FONT), HEADER_FONT, TEXT_SECONDARY, header),
    body,
    legend ? legend.svg(MARGIN, contentTop + contentHeight + LEGEND_GAP) : "",
    "</svg>",
  ]
    .filter((part) => part !== "")
    .join("\n");
}
